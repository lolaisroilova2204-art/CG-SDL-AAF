def tr(key, lang="uz", *args):
    v = STR.get(key)
    s = key if v is None else v[0 if lang == "uz" else 1]
    for i, a in enumerate(args):
        s = s.replace("{%d}" % i, str(a))
    return s


def region_name(idx, lang="uz"):
    return tr("regions", lang).split("|")[idx]
